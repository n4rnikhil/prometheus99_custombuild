"""
bake_fonts.py - turn Inter (SIL Open Font License 1.1) into tiny 2-bit
anti-aliased bitmap fonts compiled straight into the HMI (no font engine,
no files at runtime, works on bare-metal targets).

Usage:  python tools/bake_fonts.py <dir containing Inter-Regular.otf / Inter-SemiBold.otf>
Writes: src/renderer/font_inter.c

Each glyph pixel is a 2-bit coverage value (0 = empty .. 3 = solid), packed
4 pixels per byte, row-major, rows padded to a whole byte.
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "renderer", "font_inter.c")

ASCII = "".join(chr(c) for c in range(32, 127))
HERO = "0123456789.-%: "

# name, file, pixel size, charset, tabular digits
FONTS = [
    ("hmi_font_caption",  "Inter-SemiBold.otf", 11, ASCII, False),
    ("hmi_font_body",     "Inter-Regular.otf",  13, ASCII, False),
    ("hmi_font_body_b",   "Inter-SemiBold.otf", 13, ASCII, False),
    ("hmi_font_title",    "Inter-SemiBold.otf", 16, ASCII, False),
    ("hmi_font_headline", "Inter-SemiBold.otf", 22, ASCII, False),
    ("hmi_font_hero_s",   "Inter-SemiBold.otf", 30, HERO,  True),
    ("hmi_font_hero_m",   "Inter-SemiBold.otf", 46, HERO,  True),
    ("hmi_font_hero_l",   "Inter-SemiBold.otf", 66, HERO,  True),
]


def bake(path, size, charset, tabular):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    line_h = ascent + descent
    pad = size
    glyphs = []
    digit_adv = max(int(round(font.getlength(d))) for d in "0123456789")
    for ch in charset:
        adv = int(round(font.getlength(ch)))
        if tabular and ch.isdigit():
            adv = digit_adv
        img = Image.new("L", (size * 3 + pad * 2, line_h + pad * 2), 0)
        ImageDraw.Draw(img).text((pad, pad + ascent), ch, font=font, fill=255, anchor="ls")
        bbox = img.getbbox()
        if bbox is None:
            glyphs.append((ch, adv, 0, 0, 0, 0, []))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        xoff = x0 - pad
        if tabular and ch.isdigit():
            xoff += (digit_adv - int(round(font.getlength(ch)))) // 2
        yoff = y0 - pad                      # from top of line box
        rows = []
        for y in range(y0, y1):
            row = []
            for x in range(x0, x1):
                v = img.getpixel((x, y))
                row.append(min(3, (v * 3 + 127) // 255))
            rows.append(row)
        glyphs.append((ch, adv, xoff, yoff, w, h, rows))
    return line_h, ascent, glyphs


def pack(rows, w):
    out = []
    for row in rows:
        for i in range(0, w, 4):
            b = 0
            for k in range(4):
                v = row[i + k] if i + k < w else 0
                b |= v << (6 - 2 * k)
            out.append(b)
    return out


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    src_dir = sys.argv[1]
    lines = [
        "/**",
        " * @file font_inter.c",
        " * @brief GENERATED by tools/bake_fonts.py - do not edit by hand.",
        " *",
        " * Bitmaps derived from Inter, Copyright (c) 2016 The Inter Project Authors",
        " * (https://github.com/rsms/inter), licensed under the SIL Open Font License,",
        " * Version 1.1 (https://openfontlicense.org). See fonts/OFL.txt.",
        " */",
        "",
        '#include "../../include/renderer/font.h"',
        "",
    ]
    total = 0
    for name, file, size, charset, tabular in FONTS:
        line_h, ascent, glyphs = bake(os.path.join(src_dir, file), size, charset, tabular)
        bits = []
        table = []
        for ch, adv, xoff, yoff, w, h, rows in glyphs:
            off = len(bits)
            bits.extend(pack(rows, w))
            table.append((ch, adv, xoff, yoff, w, h, off))
        total += len(bits) + len(table) * 8
        lines.append(f"/* {file} {size}px, {len(table)} glyphs, {len(bits)} bytes */")
        lines.append(f"static const uint8_t {name}_bits[{max(1, len(bits))}] = {{")
        for i in range(0, max(1, len(bits)), 24):
            chunk = bits[i:i + 24] if bits else [0]
            lines.append("    " + ",".join(f"0x{b:02X}" for b in chunk) + ",")
        lines.append("};")
        lines.append(f"static const hmi_glyph_t {name}_glyphs[{len(table)}] = {{")
        for ch, adv, xoff, yoff, w, h, off in table:
            label = ch if ch not in "\\*/" else "?"
            lines.append(f"    {{ {w}, {h}, {xoff}, {yoff}, {adv}, {off} }}, /* '{label}' */")
        lines.append("};")
        first = ord(charset[0])
        contiguous = charset == ASCII
        lines.append(f"const hmi_font_t {name} = {{ {line_h}, {ascent}, {first if contiguous else 0}, "
                     f"{len(table)}, {'NULL' if contiguous else name + '_map'}, {name}_glyphs, {name}_bits }};")
        if not contiguous:
            # insert the map before the font definition
            map_line = f"static const char {name}_map[] = \"{charset}\";"
            lines.insert(len(lines) - 1, map_line)
        lines.append("")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT} ({total} bytes of font data)")


if __name__ == "__main__":
    main()
